import { readFile,access } from 'node:fs/promises';
const pkg=JSON.parse(await readFile(new URL('../package.json',import.meta.url),'utf8'));
const builder=await readFile(new URL('../electron-builder.yml',import.meta.url),'utf8');
const lock=JSON.parse(await readFile(new URL('../package-lock.json',import.meta.url),'utf8'));
const {config:site}=await import('../website/dist/config.js');
if(lock.version!==pkg.version||lock.packages[''].version!==pkg.version)throw Error('package-lock.jsonのバージョンが一致しません');
if(site.developmentVersion!==pkg.version)throw Error('配布サイトのdevelopmentVersionが一致しません');
const owner=/^  owner: (\S+)$/m.exec(builder)?.[1],repo=/^  repo: (\S+)$/m.exec(builder)?.[1];
if(owner!==site.owner||repo!==site.repository)throw Error('アプリと配布サイトのGitHub配布先が一致しません');
if(site.releaseApi!==`https://api.github.com/repos/${owner}/${repo}/releases/latest`||site.releasesUrl!==`https://github.com/${owner}/${repo}/releases`)throw Error('配布サイトのリリースURLが一致しません');
if(!builder.includes(`releaseNotesFile: docs/releases/v${pkg.version}.md`))throw Error('releaseNotesFileのバージョンが一致しません');
await access(new URL(`../docs/releases/v${pkg.version}.md`,import.meta.url));
if(/REPLACE_OWNER|REPLACE_REPO|YOUR_GITHUB/.test(builder))throw Error('GitHub Releasesの配布先を設定してください');
const tag=process.env.RELEASE_TAG;
if(tag&&tag!=='v'+pkg.version)throw Error(`タグ ${tag} と package.json ${pkg.version} が一致しません`);
for(const file of ['build/icon.png','build/icon.ico','build/icon.icns','build/icons/512x512.png','vendor/sanka/package.json'])await access(new URL('../'+file,import.meta.url));
console.log(`Release configuration ready: v${pkg.version} → ${owner}/${repo} (publishing is not performed by this check)`);
